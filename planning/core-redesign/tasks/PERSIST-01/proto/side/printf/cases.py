# The cases: (format, C arguments, Python arguments, level that should get it right). Writes own/cases.h and own/expected.txt.
import sys
L = "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ" * 3
C = [
  ("%d|%i|%u", "(int)vneg, 7, 3000000000u", (-42, 7, 3000000000), 0),
  ("%5d|%-5d|%05d", "42, 42, (int)vneg", (42, 42, -42), 0),
  ("%x|%X|%08lx", "0xbeefu, 0xbeefu, 0x1234abcdul", (0xbeef, 0xbeef, 0x1234abcd), 0),
  ("%ld|%lu", "-123456789l, 4000000000ul", (-123456789, 4000000000), 0),
  ("%c|%s|%10s|%-4s|", "'A', \"hey\", \"right\", \"l\"", ('A', 'hey', 'right', 'l'), 0),
  ("%s", "longLine", (L,), 0),
  ("%%|%.3s|%-8.2s|%8.1s|", "\"abcdef\", \"xyz\", \"q\"", ('abcdef', 'xyz', 'q'), 1),
  ("%.5d|%8.3d|%-8.3d|%.0d|%.3x", "42, 42, (int)vneg, 0, 0xau", (42, 42, -42, 0, 0xa), 1),
  ("%+d|% d|%+5d|%*d|%-*d|%.*s", "5, 5, (int)vneg, 6, 7, 4, 8, 2, \"abcd\"", (5, 5, -42, 6, 7, 4, 8, 2, 'abcd'), 1),
  ("%.2f|%f|%.0f|%.3f", "3.14159, 1.5, 7.6, -0.0005", (3.14159, 1.5, 7.6, -0.0005), 2),
  ("%8.2f|%-8.1f|%08.3f|%+.1f", "3.14159, 2.25, (double)vneg / 8, 0.05", (3.14159, 2.25, -42 / 8, 0.05), 2),
  ("%.9f|%.4f|%f", "0.123456789, 123456.78125, 1e10", (0.123456789, 123456.78125, 1e10), 2),
]
def py(fmt):
    return fmt.replace('%l', '%').replace('%-8.2s', '%-8.2s')
with open(sys.argv[1] + '/cases.h', 'w') as h:
    h.write('// generated by cases.py\n#define NCASES %d\n' % len(C))
    h.write('static const char longLine[] = "%s";\n' % L)
    h.write('static void runCase(Print &o, int i) {\n  switch (i) {\n')
    for i, (f, a, _, _) in enumerate(C):
        h.write('    case %d: OUT(o, "%s\\n", %s); break;\n' % (i, f, a))
    h.write('  }\n}\n')
with open(sys.argv[1] + '/expected.txt', 'w') as e:
    for f, _, p, lv in C:
        x = py(f) % p
        if f.startswith('%.5d|%8.3d'):
            x = x.replace('|0|', '||')  # C: precision 0 prints no digits for 0; Python prints 0
        e.write('%d\t%s\n' % (lv, x))
print(open(sys.argv[1] + '/expected.txt').read())
