static int failures, checks;

static void zone(int k)
{
    if (zones[k]) {
        setenv("TZ", zones[k], 1);
    } else {
        unsetenv("TZ");
    }
}

static int differs(const struct tm *g, const struct fields *w)
{
    return g->tm_year != w->year || g->tm_mon != w->mon || g->tm_mday != w->mday || g->tm_hour != w->hour ||
           g->tm_min != w->min || g->tm_sec != w->sec || g->tm_wday != w->wday || g->tm_yday != w->yday ||
           g->tm_isdst != w->isdst;
}

int main(void)
{
    for (size_t i = 0; i < sizeof lcs / sizeof lcs[0]; i++) {
        zone(lcs[i].zone);
        const time_t t = (time_t)lcs[i].t;
        struct tm g;
        memset(&g, 0x55, sizeof g);
        checks++;
        if (core_localtime_r(&t, &g) != &g || differs(&g, &lcs[i].want)) {
            printf("FAIL localtime_r %s %lld: %d-%d-%d %d:%d:%d wd %d yd %d dst %d\n",
                   zones[lcs[i].zone] ? zones[lcs[i].zone] : "(unset)", lcs[i].t, g.tm_year, g.tm_mon, g.tm_mday,
                   g.tm_hour, g.tm_min, g.tm_sec, g.tm_wday, g.tm_yday, g.tm_isdst);
            failures++;
        }
    }
    for (size_t i = 0; i < sizeof mks / sizeof mks[0]; i++) {
        zone(mks[i].zone);
        struct tm g;
        memset(&g, 0, sizeof g);
        g.tm_year = mks[i].in.year, g.tm_mon = mks[i].in.mon, g.tm_mday = mks[i].in.mday;
        g.tm_hour = mks[i].in.hour, g.tm_min = mks[i].in.min, g.tm_sec = mks[i].in.sec, g.tm_isdst = mks[i].in.isdst;
        const time_t t = core_mktime(&g);
        checks++;
        if ((long long)t != mks[i].t || differs(&g, &mks[i].want)) {
            printf("FAIL mktime %s case %zu: %lld %d-%d-%d %d:%d:%d wd %d yd %d dst %d, want %lld\n",
                   zones[mks[i].zone] ? zones[mks[i].zone] : "(unset)", i, (long long)t, g.tm_year, g.tm_mon,
                   g.tm_mday, g.tm_hour, g.tm_min, g.tm_sec, g.tm_wday, g.tm_yday, g.tm_isdst, mks[i].t);
            failures++;
        }
    }
    printf("checks %d failures %d\n", checks, failures);
    return failures != 0;
}
