#!/usr/bin/env python3
"""Generate bundled example profiles without a test harness or connected board."""
import argparse
import pathlib
import re
import sys

from sketch_requirements import (all_boards, ethernet_clocks, ethernet_parts, requirements,
                                 series_capabilities, target_board, unmet)

REPO = pathlib.Path(__file__).resolve().parents[2]
INDEX_URL = ("https://ch32-riscv-ug.github.io/ArduinoCore-CH32RV/"
             "package_ch32-riscv-ug_index.json")


def clock(need: dict, board: str) -> str:
    """`,clock=<id>` where an Ethernet example needs the series' Ethernet clock."""
    if "ETHERNET" in need["caps"] and board in ethernet_clocks():
        return f",clock={ethernet_clocks()[board]}"
    return ""


def render(source: pathlib.Path) -> str:
    version = re.search(r"^version=(.+)$", (REPO / "platform.txt").read_text(),
                        re.M).group(1).strip()
    need = requirements(source)
    # Every generic board (one per series, in boards.txt's order), whatever the
    # bench has: a profile declares that the example compiles there.
    capabilities = series_capabilities()
    generic_boards = [b for b in all_boards() if b in capabilities]
    lines = [
        "# Generated by tools/generate/sync_example_profiles.py - do not edit.",
        f"# What this example requires is declared in {source.name}.ino;",
        "# see docs/examples-build-rules.ja.md.",
        "",
        "profiles:",
    ]
    kept = []
    fixed = target_board(source)
    if fixed:
        name = fixed.split(":")[0].lower()
        lines.extend([
            f"  {name}:",
            f"    fqbn: ch32-riscv-ug:ch32rv:{fixed}",
            "    platforms:",
            f"      - platform: ch32-riscv-ug:ch32rv ({version})",
            f"        platform_index_url: {INDEX_URL}",
            "",
            f"default_profile: {name}",
            "",
        ])
        return "\n".join(lines)
    def profile(name: str, fqbn: str) -> None:
        kept.append(name)
        lines.extend([
            f"  {name}:",
            f"    fqbn: ch32-riscv-ug:ch32rv:{fqbn}",
            "    platforms:",
            f"      - platform: ch32-riscv-ug:ch32rv ({version})",
            f"        platform_index_url: {INDEX_URL}",
            "",
        ])

    for board in generic_boards:
        reason = unmet(need, board)
        if not reason:
            profile(board.lower(), f"{board}:pnum=ANY{clock(need, board)}")
            continue
        lines.append(f"  # {board}: omitted, {reason}")
        # A part with what its series' ANY entry lacks (CH32V203RBT6's
        # Ethernet): an example that needs it builds there, in the series'
        # place, with the part selected. Only for that: an example the ANY
        # entry is merely too small for stays omitted.
        if "ETHERNET" in need["caps"]:
            for part, series in ethernet_parts().items():
                if series == board and not unmet(need, board, part):
                    profile(part.lower(), f"{board}:pnum={part}{clock(need, board)}")
    if not kept:
        raise ValueError(f"{source}: no generic board satisfies requirements")
    # No default_profile: no series is the example's own, and arduino-cli
    # takes -b or --profile. A board-specific example (above) keeps its one.
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for ino in sorted((REPO / "libraries").glob("*/examples/*/*.ino")):
        if ino.stem != ino.parent.name:
            continue
        destination = ino.parent / "sketch.yaml"
        wanted = render(ino.parent)
        if destination.is_file() and destination.read_text() == wanted:
            continue
        stale.append(str(destination.relative_to(REPO)))
        if not args.check:
            destination.write_text(wanted)
    if args.check and stale:
        print("Profiles differ; run tools/generate/sync_example_profiles.py:",
              file=sys.stderr)
        print("\n".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
